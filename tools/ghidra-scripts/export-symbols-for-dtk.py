# used to track cases where the same file name appears
# multiple times.
FILE_NAME_STRINGS = {} # addr => name

def findCall(caller, addrCall):
    """Scan through 'caller' and find the first address
    at which it calls/jumps to 'addrCall'.
    addrCall should be an Address object."""
    addrStart = caller.body.minAddress
    addrEnd   = caller.body.maxAddress
    addressSetView = AF.getAddressSet(addrStart, addrEnd)
    instrs = listing.getInstructions(addressSetView, True)
    for i, instr in enumerate(instrs):
        for addrDst in instr.getFlows():
            if addrDst == addrCall:
                return instr.getAddress()
    return None

def assignTagsFromCall(funcAddr, paramIdx):
    """Check every function that calls the function at
    'funcAddr'. Retrieve the source file name from the
    parameter 'paramIdx' and tag the calling function
    with that name.
    """
    addrObj = intToAddr(funcAddr)
    func = getFunctionAt(addrObj)
    monitor.setMessage("Finding calls to " + str(func.getName()))
    for caller in func.getCallingFunctions(monitor):
        # find where exactly this is called from
        callAddr = findCall(caller, addrObj)
        if callAddr is None: continue

        # extract the desired parameter from that call
        prop  = analyzeFunction(caller, monitor)
        instr = listing.getCodeUnitAt(callAddr)
        # XXX hardcoded register for PPC
        val = prop.getRegisterValue(callAddr,
            instr.getRegister('r%d' % (paramIdx + 3)))
        if val is None:
            printf("an't find param for call to %s at 0x%X",
                str(func.getName()), addrToInt(callAddr))
            continue
        val = val.getValue() & 0xFFFFFFFF

        # the value should be the address of a string
        fileName, nameLen = readString(intToAddr(val))
        oldName = fileName
        if val in FILE_NAME_STRINGS:
            fileName = FILE_NAME_STRINGS[val]

        # see if this name appears at another address.
        # this can happen when the same file name is used
        # multiple times (because the same library was linked
        # multiple times, or the directory name wasn't preserved).
        # if we don't distinguish them, we'll end up lumping
        # everything between the two files together.
        for nameAddr, nameVal in FILE_NAME_STRINGS.items():
            if nameVal == fileName and nameAddr != val:
                printf("Multiple instances of file name: %s (0x%X, 0x%X)",
                    fileName, val, nameAddr)
                # stuff the address in to distinguish it
                nameStart = re_splitFileName.match(fileName).group(1)
                fileName = '%s.%08x%s' % (nameStart, val,
                    fileName[len(nameStart):])
                #printf(" => %s", fileName)
        FILE_NAME_STRINGS[val] = fileName

        # remove existing tags
        oldTags = funcGetFileNameTags(caller)
        for tag in oldTags: caller.removeTag(tag)

        # tag the caller with this name
        printf("Func 0x%X %s tag %s",
            addrToInt(caller.body.minAddress),
            caller.getName(), fileName)
        #if fileName != oldName: caller.removeTag(oldName)
        caller.addTag(fileName)

def assignTagsToFunctions():
    """For each function listed in ASSERT_FUNCS which has
    a 'file' parameter, iterate all calls to it.
    Tag the calling functions with that name.
    """
    for addr, params in ASSERT_FUNCS.items():
        for i, param in enumerate(params):
            if param == 'file':
                assignTagsFromCall(addr, i)

def getFuncTagRanges(funcs):
    """Find the first and last function with each filename tag."""
    monitor.setIndeterminate(False)
    monitor.setMessage("Checking function file ranges...")
    tagRanges = {} # tag => [min, max func start addrs]
    filt  = lambda t: str(t).lower().endswith(SRC_FILE_EXTENSIONS)

    # find the first and last address of each tag
    monitor.setProgress(0)
    monitor.setMaximum(len(funcs))
    for func in funcs:
        checkCanceled()
        tags = list(func.getTags())
        for tag in filter(filt, tags):
            name = str(tag).lower()
            if name not in tagRanges:
                tagRanges[name] = [func.body.minAddress, func.body.minAddress]
            else:
                tagRanges[name][0] = min(tagRanges[name][0], func.body.minAddress)
                tagRanges[name][1] = max(tagRanges[name][1], func.body.maxAddress)
        monitor.incrementProgress(1)
    return tagRanges

def funcGetFileNameTags(func):
    """Return all filename tags for this function."""
    return set(
        filter(lambda t: t.lower().endswith(SRC_FILE_EXTENSIONS),
            map(str, func.getTags())
        )
    )

def fillFuncTagGaps():
    """Find the first and last function with each filename
    tag. Assign that tag to functions in between them.
    """
    funcs = list(listing.getFunctions(True))
    tagRanges = getFuncTagRanges(funcs)

    # assign tags to functions in the gaps
    monitor.setMessage("Filling file gaps...")
    monitor.setProgress(0)
    monitor.setMaximum(len(tagRanges.items()))
    for name, fileRange in tagRanges.items():
        printf("Tag '%s' range is 0x%X - 0x%X", name,
            addrToInt(fileRange[0]), addrToInt(fileRange[1]))
        addr = fileRange[0]
        prevFunc = None
        while addr < fileRange[1]:
            func = getFunctionContaining(addr)
            if func is None:
                if prevFunc is not None:
                    printf("Function gap at 0x%X", addrToInt(addr))
            else:
                funcTags = funcGetFileNameTags(func)
                funcTags.add(name)
                if len(funcTags) > 1:
                    printf("Function 0x%X '%s' has multiple file tags: %s",
                        addrToInt(addr), func.getName(), funcTags)
                    # ...what do we do about it?
                    # some have several tags.
                if len(funcTags) == 0 or funcTags == [name]:
                    # adding the same tag again is harmless
                    printf("Func 0x%X '%s' is in '%s'", addrToInt(addr),
                        func.getName(), name)
                    func.addTag(name)
                else:
                    # add it again anyway because ghidra is dumb and
                    # will report it having a tag when it doesn't
                    func.addTag(name)
                addr = func.body.maxAddress
            prevFunc = func
            addr = addr.add(4)
        monitor.incrementProgress(1)

def fixTagCases():
    """Correct functions that have the same tag twice
    differing in letter case.
    """
    monitor.setIndeterminate(False)
    monitor.setMessage("Correcting function tag cases...")
    filt  = lambda t: str(t).lower().endswith(SRC_FILE_EXTENSIONS)
    funcs = list(listing.getFunctions(True))
    monitor.setProgress(0)
    monitor.setMaximum(len(funcs) * 2)

    # some funcs have ONLY the lowercase version,
    # so first, get all lowercase-only tags, and all
    # not-lowercase-only tags.
    nonLowerTags = set()
    lowerTags    = set()
    for func in funcs:
        checkCanceled()
        tags = list(func.getTags())
        for tag in map(str, filter(filt, tags)):
            if tag.lower() == tag: lowerTags.add(tag)
            else: nonLowerTags.add(tag)
        monitor.incrementProgress(1)

    # remove tags that aren't repeats
    printf("Total tags: %d", len(nonLowerTags))
    removeTags = set()
    for tag in list(nonLowerTags):
        checkCanceled()
        if tag.lower() not in lowerTags:
            removeTags.add(tag)
            printf("Keep tag: %s", tag)
    for tag in list(removeTags):
        try: nonLowerTags.remove(tag)
        except KeyError: pass
    # nonLowerTags now contains the canonical versions of
    # all tags that appear in lowerTags.
    printf("%d duplicate tags", len(nonLowerTags))
    #for tag in nonLowerTags: printf(" %s", tag)

    # remove every tag that appears in both sets.
    nRemove = 0
    #nonLowerTags = list(nonLowerTags)
    for func in funcs:
        checkCanceled()
        lol = list(map(str, func.getTags()))
        for tag in nonLowerTags:
            tagL = tag.lower()
            # removing a tag from a function that doesn't
            # have any tags puts ghidra into an endless loop
            if tagL in lol:
                printf("Remove tag %s from %s", tagL, func.getName())
                func.removeTag(tagL)
                nRemove += 1
        monitor.incrementProgress(1)
    printf("Removed %d tags", nRemove)

def fixMultiTags():
    """If a function has multiple filename tags,
    remove them all except (if present) one that's
    the same as the function's namespace.
    """
    monitor.setIndeterminate(False)
    monitor.setMessage("Correcting functions with multiple files...")
    filt  = lambda t: str(t).lower().endswith(SRC_FILE_EXTENSIONS)
    funcs = list(listing.getFunctions(True))
    monitor.setProgress(0)
    monitor.setMaximum(len(funcs))
    for func in funcs:
        checkCanceled()
        nameTags = map(str, filter(filt, func.getTags()))
        if len(nameTags) > 1: # has more than one name tag
            printf("Func 0x%X '%s' has multiple files: %s",
                addrToInt(func.body.minAddress), func.getName(),
                nameTags)

            # get parent namespace name if any
            canonName = None
            ns = func.getParentNamespace()
            nsName = ns.getName() if ns is not None else ''
            nsNameL = nsName.lower()

            # check if adding a source file extension to the namespace
            # name produces an existing tag
            lowerTags = list(map(lambda s: s.lower(), nameTags))
            for ext in SRC_FILE_EXTENSIONS:
                if (nsNameL+ext) in lowerTags:
                    canonName = (nsName+ext)
                    printf("Canonical name is '%s'", canonName)
                    break

            # remove all tags except the canonical one
            for tag in nameTags:
                if tag != canonName:
                    func.removeTag(tag)
        monitor.incrementProgress(1)

