def getOverlappingSymbol(start, length):
    """If this range partially overlaps a symbol,
    return that symbol and its address range.
    Otherwise, return None.
    """
    end = start+length-1
    for addr in range(start, end):
        objStart, objEnd = None, None
        addrObj = intToAddr(addr)
        obj = getFunctionContaining(addrObj)
        if obj is not None:
            objStart = addrToInt(obj.body.minAddress)
            objEnd   = addrToInt(obj.body.maxAddress)+1
        else:
            obj = getDataContaining(addrObj)
            if obj is not None:
                objStart = addrToInt(obj.getMinAddress())
                objEnd   = addrToInt(obj.getMaxAddress())+1
        if obj is None: continue
        if objStart != start: return obj, objStart, objEnd
        if objEnd != end: return obj, objStart, objEnd
    return None, None, None

def readSymbolsTxt(path):
    symbols = {}
    with open(path, 'r') as file:
        for line in file.readlines():
            com = line.find('#')
            if com >= 0: line = line[0:com]
            parts = re_symbolsTxt.match(line)
            if parts is None: continue
            name   = parts.group(1)
            sec    = parts.group(2)
            addr   = parts.group(3)
            params = parts.group(4)
            addr   = int(addr, 0)
            params = params.split()
            if name in symbols:
                printf("symtxt: Duplicate symbol name: %s", name)
            lbl = getLabelAt(intToAddr(addr))
            if lbl is not None and lbl != name:
                obj = getFunctionAt(intToAddr(addr))
                if obj is not None:
                    try: ns = obj.getParentNamespace()
                    except AttributeError: ns = None
                    if ns is not None and ns.getName() != 'Global':
                        lbl = ns.getName() + '_' + lbl
                printf("symtxt: using ghidra name '%s' instead of symtxt name '%s' at 0x%X",
                    lbl, name, addr)
                name = lbl
            sym = {
                'name':    name,
                'address': addr,
                'section': sec,
            }
            printf("symtxt: 0x%X %s %s", addr, sec, name)
            symbols[name] = sym
            for param in params:
                param = param.split(':')
                if param[0] == 'size': param[1] = int(param[1], 0)
                try: sym[param[0]] = param[1]
                except IndexError: sym[param[0]] = True
    return symbols

def correctJumpTables(symbols):
    """Make jump tables arrays because ghidra decided
    to stop doing that.
    """
    for name, sym in symbols.items():
        if not name.startswith(('jumptable', 'switchdata')): continue
        addr    = sym['address']
        addrObj = intToAddr(addr)

        # get the next defined data
        dNext   = addrToInt(getDataAfter(addrObj).getMinAddress())
        count   = (dNext - addr) // SIZEOF_POINTER

        # scan to see if all entries are valid
        for i in range(count):
            b1 = getUnsignedByte(intToAddr(addr+(i*4)))
            b2 = getUnsignedByte(intToAddr(addr+(i*4)+1))
