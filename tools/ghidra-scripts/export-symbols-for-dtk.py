def writeSymbolsTxt(outPath, files, symbols):
    # build a map of address => file/section
    addrMap = [] # (start, end, file, sectionName)
    for name, srcFile in files.items():
        for secName in SECTION_NAMES:
            if secName not in srcFile: continue
            sec = srcFile[secName]
            aMin = sec['min']
            aMax = sec['max']
            addrMap.append((aMin, aMax, srcFile, secName))

    monitor.setIndeterminate(False)
    monitor.setMessage("Writing symbols...")
    monitor.setProgress(0)
    monitor.setMaximum(SYMBOL_MAX_ADDR - SYMBOL_MIN_ADDR)
    outSymbols = {}
    outAddrs   = {}

    nextAddr = intToAddr(SYMBOL_MIN_ADDR)
    prevAddr = addrToInt(nextAddr)
    while True:
        # getSymbolAfter() is broken and skips some symbols
        # this appears to be intended because it skips
        # "non-default" symbols, whatever those are, while
        # getSymbolAt() doesn't.
        while addrToInt(nextAddr) < SYMBOL_MAX_ADDR:
            if nextAddr in IGNORE_SYMBOLS:
                nextAddr = nextAddr.add(4)
                continue
            sym = getSymbolAt(nextAddr)
            nextAddr = nextAddr.add(1)
            # break once we find a symbol
            # excluding labels within functions
            if sym is not None:
                if isSymbolALocalLabel(sym):
                    printf("Skip 0x%X %s because is local",
                        addrToInt(sym.getAddress()), sym.getName(True))
                else: break
        if sym is None: break
        addrObj = sym.getAddress()
        addr = addrToInt(addrObj)
        monitor.setProgress(addr - SYMBOL_MIN_ADDR)

        symName = sym.getName(True)
        printf("Export symbol: %s", symName)
        if '::override::' in symName: continue
        if symName.startswith(COMMON_PREFIXES): continue
        if symName in AUTO_SYMBOLS: continue
        if re_switchCase.match(symName): continue
        if symName.startswith('s_') or symName.startswith('u_'):
            # the generated name is often not valid
            symName = 's_%08X' % addr
        if '[' in symName: continue
        if '.' in symName: continue
        if '+' in symName: continue

        # change to match dtk naming scheme for unnamed funcs
        if symName.startswith('FUN_'):
            symName = 'fn' + symName[3:].upper() # 'FUN_abc' -> 'fn_ABC'
        symName = symName.replace('::', '_').replace('[', '_') \
            .replace(']', '').replace('.', '_')
        prevAddr = addrToInt(nextAddr)

        # get the section
        symSection = None
        for entry in addrMap:
            if addr >= entry[0] and addr < entry[1]:
                symSection = entry[3]
                break
        # fall back to block-name-based check (less accurate)
        if symSection is None: symSection = getSectionTypeAt(addr)
        if symSection is None:
            printf("No section for symbol 0x%X: %s",
                addr, symName)
            continue
            #symSection = "unk"
        if not symSection.startswith('.'):
            symSection = '.'+symSection

        # get the object type, data type, and size
        symType, symSize, symData = 'object', None, None
        func = getFunctionAt(addrObj)
        tags = []
        if func is not None:
            tags = list(map(lambda t: str(t), func.getTags())) # lol
            if 'fakesymbol' in tags:
                printf("Ignoring func '%s' (0x%X) due to fakesymbol tag",
                    symName, addr)
                continue
            symType = 'function'
            symSize = (addrToInt(func.body.maxAddress) - addr)+1
            if symSize < 0: symSize = 0
        else:
            data = getDataAt(addrObj)
            if data is None: symSize = 4
            else:
                symSize = data.getLength()
                symData = data.getBaseDataType().getName()
                if '*' in symData: symData = '4byte'
                if symData.startswith('char['): symData = 'string'
                elif symData == 'string':
                    symData = 'string'
                    # ghidra seems to include the null byte
                    # but dtk does not
                    symSize -= 1
                elif '[' in symData: symData = None
                symData = TYPE_NAME_MAP.get(symData, symData)
                if symData not in VALID_DATA_TYPES:
                    if   symSize == 1: symData = 'byte'
                    elif symSize == 2: symData = '2byte'
                    elif symSize == 4: symData = '4byte'
                    elif symSize == 8: symData = '8byte'
                    else: symData = None
        #printf("0x%X %s (%s) %s %s", addr, symType, str(symData),
        #    symName, str(tags))

        # get info from original symbols.txt
        extInfo = []
        symTxt = symbols.get(symName, {})
        symTxt['size'] = symSize
        for k, v in symTxt.items():
            if k == 'size': v = '0x%X' % v
            if k in IGNORE_FIELDS: pass
            elif v == True: extInfo.append(k)
            else: extInfo.append('%s:%s' % (k, str(v)))
        if symData is not None:
            extInfo.append('data:'+str(symData))

        outSymbols[symName] = {
            'name': symName,
            'section': symSection,
            'addr': addr,
            'type': symType,
            'ext':  extInfo,
        }
        outAddrs[addr] = symName

    # merge original symbols.txt data into this
    for name, symTxt in symbols.items():
        # skip those we've already got from ghidra
        if name in outSymbols: continue
        if name in AUTO_SYMBOLS: continue
        if '::override::' in name: continue
        if '_override_' in name: continue
        if name.startswith(COMMON_PREFIXES): continue
        if name in AUTO_SYMBOLS: continue
        if re_switchCase.match(name): continue
        if symTxt['address'] in outAddrs: continue
        extInfo = []
        symSize = None
        for k, v in symTxt.items():
            if k == 'size':
                symSize = v
                v = '0x%X' % v
            if k in IGNORE_FIELDS: pass
            elif v == True: extInfo.append(k)
            else: extInfo.append('%s:%s' % (k, str(v)))
        if symTxt['section'] == '.unk':
            sec = getSectionTypeAt(symTxt['address'])
            if sec is not None:
                symTxt['section'] = '.' + sec
            else: continue

        # if this overlaps another symbol, discard it
        overlap = None
        if symSize is not None:
            overlap, ovlAddr, ovlEnd = getOverlappingSymbol(
                symTxt['address'], symSize+1)
            if overlap is not None:
                ovlName = "?"
                try: ovlName = str(overlap.getName(True))
                except: pass
                printf("symbols.txt: Ignoring 0x%X - 0x%X '%s' "
                    "because it overlaps 0x%X - 0x%X '%s'",
                    symTxt['address'], symTxt['address']+symSize, name,
                    ovlAddr, ovlEnd, ovlName)
                continue

        printf("symbols.txt: '%s' @ 0x%X", name, symTxt['address'])
        outSymbols[name] = {
            'name': name,
            'section': symTxt['section'],
            'addr': symTxt['address'],
            'type': symTxt['type'],
            'ext':  extInfo,
        }

    sortedSyms = list(outSymbols.values())
    sortedSyms.sort(key=lambda s: s['addr'])

    with open(outPath + '/symbols.txt', 'wt') as outFile:
        for sym in sortedSyms:
            ext = sym['ext']
            outFile.write(
                '%s = %s:0x%08X; // type:%s %s\n' % (
                sym['name'], sym['section'], sym['addr'],
                sym['type'], ' '.join(ext)))

