def fileHasAnySplits(srcFile):
    for secName in SECTION_NAMES:
        if secName in srcFile:
            sec = srcFile[secName]
            aMin = sec['min']
            aMax = sec['max']
            if aMin < aMax: return True
    return False

def writeSplitsTxt(inPath, outPath, files, symbols, headerItems):
    # sort the split info
    # must be in order of address!
    monitor.setIndeterminate(True)
    monitor.setMessage("Sorting...")
    sortedFiles = []
    for name, srcFile in files.items():
        sortedFiles.append((name, srcFile))
    sortedFiles.sort(key=_sortFilesKey)

    # write the split info
    monitor.setIndeterminate(False)
    monitor.setMessage("Writing splits...")
    monitor.setProgress(0)
    monitor.setMaximum(len(sortedFiles))
    with open(outPath + '/splits.txt', 'wt') as outFile:
        outFile.write('Sections:\n')
        for item in headerItems:
            outFile.write('\t%-12stype:%s align:%s\n' % (
                item['name'], item['type'], item['align']))
        for name, srcFile in sortedFiles:
            monitor.incrementProgress(1)
            if name == 'main/main.c':
                printf("Splits for %s:", name)
                for secName in SECTION_NAMES:
                    if secName in srcFile:
                        sec = srcFile[secName]
                        printf("%s: 0x%X - 0x%x", secName,
                            sec['min'], sec['max'])
                    else: printf("%s: not present", secName)
            if name == 'unknown': continue
            if name.endswith('.h'): continue
            if name.startswith('unk'): continue
            if name in IGNORE_FILES: continue
            if not fileHasAnySplits(srcFile):
                printf("Skipping %s (no splits)", name)
                continue
            printf("Writing splits for %s", name)
            outFile.write('\n%s:\n' % name)
            for secName in SECTION_NAMES:
                if secName not in srcFile: continue
                sec = srcFile[secName]
                aMin = sec['min']
                aMax = sec['max']
                if aMin in IGNORE_SPLITS: continue
                if aMin < aMax:
                    outFile.write('\t.%s\tstart:0x%08X end:0x%08X\n' % (
                        secName, aMin, aMax))

